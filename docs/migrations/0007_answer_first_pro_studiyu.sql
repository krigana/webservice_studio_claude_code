-- Переписано перший абзац сторінки «Про студію» (/pro-studiyu) у форматі
-- "answer-first" — перше речення тепер самодостатня відповідь на "хто
-- такі Webservice Studio і чим займаються" (для кращого цитування в
-- Google AI Overviews/AI Mode, ChatGPT Search). REPLACE() змінює лише
-- цей конкретний абзац, решта контенту сторінки лишається як є; якщо
-- абзац уже був відредагований вручну через /admin/pages/ і не
-- збігається побайтово з оригіналом — REPLACE() просто нічого не
-- знайде і safely не змінить нічого (запуск безпечний і при повторному
-- виконанні).

