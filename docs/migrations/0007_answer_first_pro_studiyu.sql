SET content = REPLACE(
    content,
    '<p>Webservice Studio — веб-студія повного циклу: розробляємо сайти й застосунки, налаштовуємо інструменти для арбітражу трафіку та адмініструємо домени й хостинг — від першого макета до підтримки після запуску.</p>',
    '<p>Webservice Studio — синельниківська веб-студія повного циклу, яка розробляє сайти та Android-застосунки, готує вайтпейджі, лендинги й клоакінг для арбітражу трафіку та адмініструє домени й хостинг клієнтів. Працюємо від першого макета до підтримки після запуску, без залучення підрядників під кожну окрему задачу.</p>'
)
WHERE slug = 'pro-studiyu';
