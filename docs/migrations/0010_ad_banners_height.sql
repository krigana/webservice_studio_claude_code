-- Дозволяємо задавати висоту показу кожного банера окремо (px) —
-- користувач попросив можливість самому керувати розміром банера, а не
-- лише фіксованим значенням із CSS (раніше було жорстко 180px
-- десктоп/110px мобільна, однаково для всіх банерів).
--
-- NULL (типово) — банер показується зі старою фіксованою висотою з CSS
-- (.ad-banner__img: 180px десктоп / 110px мобільна) — старі банери без
-- заданого значення не зміняться після цієї міграції.

ALTER TABLE ad_banners
    ADD COLUMN max_height SMALLINT UNSIGNED NULL
        COMMENT 'бажана висота показу банера в px; NULL — типова висота з CSS'
        AFTER alt_text;
