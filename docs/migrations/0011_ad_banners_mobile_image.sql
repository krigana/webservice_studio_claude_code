-- Окреме зображення банера для маленьких екранів (мобільна версія) —
-- користувач попросив можливість завантажити другу, вужчу картинку, яка
-- підміняє основну на мобільних. NULL (типово) — на мобільній
-- показується та сама основна картинка, що й на десктопі (як і раніше).

ALTER TABLE ad_banners
    ADD COLUMN image_path_mobile VARCHAR(255) NULL
        COMMENT 'опційна картинка для мобільних екранів; NULL — показується основна image_path'
        AFTER image_path;
